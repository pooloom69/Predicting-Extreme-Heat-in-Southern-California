import numpy as np

np.random.seed(42)

import pandas as pd

DATA_FILE = "Final_SOCal_dataset.csv"
TRAIN_END_YEAR = 2015          # train: 1950–2015, test: 2016–2025

data = pd.read_csv(DATA_FILE)
data.head()

data.info()

A_FEATURES = ["tmin_lag1", "dtr_lag1", "dayofyear", "days_since_rain",
              "prcp_sum30", "prcp_lag1", "oni_lag", "station_code", "year"]
A_TARGETS = ["hot_day", "hot_night"]

task_a = data[A_FEATURES + A_TARGETS]
print("Rows before removing missing values:", len(task_a))
task_a = task_a.dropna()
print("Rows after removing missing values: ", len(task_a))

a_train = task_a[task_a["year"] <= TRAIN_END_YEAR]
a_test = task_a[task_a["year"] > TRAIN_END_YEAR]
