a_train[A_TARGETS].mean()

from sklearn.ensemble import RandomForestClassifier

def train_classifier(X_train, y_train):
    model = RandomForestClassifier(n_estimators=100, class_weight="balanced",
                                   n_jobs=-1, random_state=42)
    model.fit(X_train, y_train)
    return model

a_full_models = {}
for target in A_TARGETS:
    a_full_models[target] = train_classifier(a_train[A_FEATURES], a_train[target])
    print("Trained full model for", target)

def plot_importance(model, features, title):
    importance = pd.Series(model.feature_importances_, index=features).sort_values()
    importance.plot(kind="barh", figsize=(6, 4), grid=True)
    plt.axvline(importance.mean(), color="r", linestyle="--", label="average")
    plt.title(title)
    plt.xlabel("Feature importance")
    plt.legend()
    plt.show()
    return importance

def select_features(model, features):
    importance = pd.Series(model.feature_importances_, index=features)
    return importance[importance >= importance.mean()].sort_values(ascending=False).index.tolist()

a_selected = {}
for target in A_TARGETS:
    plot_importance(a_full_models[target], A_FEATURES, f"Task A – {target}")
    a_selected[target] = select_features(a_full_models[target], A_FEATURES)
    print(target, "selected features:", a_selected[target])

